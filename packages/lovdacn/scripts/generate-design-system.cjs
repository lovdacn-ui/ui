function createCustomizerRecipesSource() {
  const recipes = {};
  for (const style of activeStyles) {
    const css = fs.readFileSync(
      path.join(DESIGN_ROOT, "styles", `style-${style}.css`),
      "utf8",
    );
    const styleMap = parseCssStyleSheet(css);
    assertRequiredMarkers(style, styleMap, REQUIRED_CUSTOMIZER_MARKERS);
    const component = (marker, target = "all") =>
      resolveMarker(styleMap, marker, target);
    recipes[style] = {
      components: {
        button: {
          container: mergeClasses(
            component("cn-button", "container"),
            component("cn-button-size-default", "container"),
          ),
          default: component("cn-button-variant-default", "container"),
          outline: component("cn-button-variant-outline", "container"),
          small: component("cn-button-size-sm", "container"),
          text: mergeClasses(
            component("cn-button", "text"),
            component("cn-button-size-default", "text"),
          ),
          smallText: component("cn-button-size-sm", "text"),
        },
        card: {
          shell: component("cn-card", "container"),
          header: component("cn-card-header", "container"),
          title: component("cn-card-title", "text"),
          description: component("cn-card-description", "text"),
          content: component("cn-card-content", "container"),
        },
        input: component("cn-input"),
        label: component("cn-label", "text"),
        badge: {
          shell: mergeClasses(
            component("cn-badge", "container"),
            component("cn-badge-variant-outline", "container"),
          ),
          text: mergeClasses(
            component("cn-badge", "text"),
            component("cn-badge-variant-outline", "text"),
          ),
        },
        checkbox: component("cn-checkbox"),
        checkboxIndicator: component("cn-checkbox-indicator"),
        progress: component("cn-progress"),
        progressIndicator: component("cn-progress-indicator"),
        separator: component("cn-separator"),
      },
      layout: styleMetadata[style].layout,
      typography: styleMetadata[style].typography,
      icon: styleMetadata[style].icon,
      block: blockRecipes[style],
    };
  }
  const serialized = literal(recipes);
  assertNoRecipeMarkers(serialized, "customizer recipe map");
  const sourceHash = crypto
    .createHash("sha256")
    .update(serialized)
    .digest("hex")
    .slice(0, 16);
  return `${GENERATED_HEADER}
import type { PresetStyle } from './preset-catalog'

export const CUSTOMIZER_RECIPE_VERSION = ${JSON.stringify(`${catalog.catalogVersion}-${sourceHash}`)} as const
export const CUSTOMIZER_RECIPES = ${serialized} as const
export type CustomizerRecipe = (typeof CUSTOMIZER_RECIPES)[PresetStyle]

export function getCustomizerRecipe(style: PresetStyle): CustomizerRecipe {
  return CUSTOMIZER_RECIPES[style]
}
`;
}

