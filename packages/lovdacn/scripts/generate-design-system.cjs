const stale = [];
function emit(relativePath, content) {
  const target = path.join(WORKSPACE_ROOT, relativePath);
  const normalized = content.replace(/\r\n/g, "\n");
  const current = fs.existsSync(target)
    ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n")
    : null;
  if (current === normalized) return;
  if (CHECK) {
    stale.push(relativePath);
    return;
  }
  fs.ensureDirSync(path.dirname(target));
  fs.writeFileSync(target, normalized, "utf8");
  console.log(`generated ${relativePath}`);
}

function emitJson(relativePath, value) {
  emit(relativePath, `${JSON.stringify(value, null, 2)}\n`);
}

function generate() {
  validateSources();
  const catalogSource = createPresetCatalogSource();
  emit("packages/lovdacn/src/preset/generated-catalog.ts", catalogSource);
  emit("apps/v2/app/create/generated/preset-catalog.ts", catalogSource);
  emit("apps/preview/src/lib/generated/preset-catalog.ts", catalogSource);
  emit(
    "apps/preview/src/lib/generated/customizer-recipes.ts",
    createCustomizerRecipesSource(),
  );
  emit(
    "apps/preview/src/components/design-system/generated-font-loader.ts",
    createPreviewFontLoaderSource(),
  );

  for (const library of activeIcons) {
    emit(
      `apps/preview/src/components/design-system/icons/${library}.tsx`,
      createPreviewIconAdapterSource(library),
    );
  }

  emitJson("apps/v2/public/schema.json", createSchema());

  const activeStyleIndex = catalog.styles.map(
    ({ name, label, description }) => ({ name, label, description }),
  );
  emitJson(
    registryChannel.registryRelative("styles/index.json"),
    activeStyleIndex,
  );

  for (const style of activeStyles) {
    const css = fs.readFileSync(
      path.join(DESIGN_ROOT, "styles", `style-${style}.css`),
      "utf8",
    );
    emit(
      registryChannel.registryRelative(`styles/style-${style}.css`),
      css.replace(/\r\n/g, "\n"),
    );
  }

  for (const engine of catalog.engines) {
    for (const library of activeIcons) {
      const source = createRegistryIconSource(library);
      const item = {
        $schema: "https://lovdacn.vercel.app/schema/registry-item.json",
        name: "semantic-icon",
        type: "registry:ui",
        dependencies: [iconPackages[library], "react-native-svg"],
        registryDependencies: [],
        files: [
          {
            path: "components/ui/semantic-icon.tsx",
            content: source,
            type: "registry:ui",
          },
        ],
        meta: { engine, iconLibrary: library },
      };
      emitJson(
        registryChannel.registryRelative(
          `icons/${engine}/${library}/semantic-icon.json`,
        ),
        item,
      );
    }
  }

  if (CHECK && stale.length > 0) {
    throw new Error(
      `Generated design-system artifacts are stale:\n- ${stale.join("\n- ")}\nRun pnpm --filter lovdacn design-system:generate.`,
    );
  }
  console.log(`   ${registryChannel.describe()}`);
  console.log(
    CHECK
      ? "design-system artifacts are current"
      : "design-system generation complete",
  );
}

generate();
