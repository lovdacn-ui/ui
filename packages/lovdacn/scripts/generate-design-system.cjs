function validateSources() {
  if (wire.version !== "a")
    throw new Error('The immutable v1 prefix must remain "a"');
  const expectedFields = [
    "style",
    "baseColor",
    "theme",
    "chartColor",
    "font",
    "iconLibrary",
    "radius",
  ];
  if (
    wire.fields.map((field) => field.key).join(",") !== expectedFields.join(",")
  ) {
    throw new Error("wire-v1.json field order changed");
  }

  const activeStyles = catalog.styles.map((style) => style.name);
  const activeIcons = Object.keys(iconManifest.libraries);
  const activeFonts = Object.keys(fontManifest);
  for (const [label, values, expected] of [
    [
      "style",
      activeStyles,
      ["luma", "lyra", "maia", "mira", "nova", "rhea", "sera", "vega"],
    ],
    [
      "icon library",
      activeIcons,
      ["lucide", "phosphor", "tabler", "expo", "heroicons"],
    ],
    // Every historical v1 font is directly supported, so the active catalog must match
    // the immutable wire order exactly — no font may be aliased away.
    ["font", activeFonts, wireValues("font")],
  ]) {
    if (values.join(",") !== expected.join(",")) {
      throw new Error(
        `Active ${label} catalog differs from the approved order: ${values.join(", ")}`,
      );
    }
  }

  for (const style of activeStyles) {
    const cssPath = path.join(DESIGN_ROOT, "styles", `style-${style}.css`);
    if (!fs.existsSync(cssPath))
      throw new Error(`Missing canonical recipe: ${cssPath}`);
    if (!styleMetadata[style])
      throw new Error(`Missing style metadata for ${style}`);
    if (!blockRecipes[style])
      throw new Error(`Missing block recipe for ${style}`);
  }

  for (const [key, icon] of Object.entries(iconManifest.icons)) {
    if (!icon.export)
      throw new Error(`Icon "${key}" is missing an export name`);
    for (const library of activeIcons) {
      if (!icon[library])
        throw new Error(`Icon "${key}" is missing its ${library} mapping`);
    }
  }

  const exportedNames = Object.values(iconManifest.icons).map(
    (icon) => icon.export,
  );
  if (new Set(exportedNames).size !== exportedNames.length) {
    throw new Error("Semantic icon export names must be unique");
  }

  for (const [font, metadata] of Object.entries(fontManifest)) {
    for (const face of ["regular", "medium", "semibold", "bold"]) {
      if (!metadata.faces[face])
        throw new Error(`Font "${font}" is missing ${face}`);
    }
  }

  validateThemeTokens();
}

