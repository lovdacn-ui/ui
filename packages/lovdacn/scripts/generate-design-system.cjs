function normalizeValue<T extends readonly string[]>(
  value: unknown,
  active: T,
  aliases: Readonly<Record<string, T[number]>>,
  fallback: T[number],
  field: string,
  warnings: string[]
): T[number] {
  const candidate = typeof value === 'string' ? value : ''
  if ((active as readonly string[]).includes(candidate)) return candidate as T[number]
  const normalized = aliases[candidate]
  if (normalized && (active as readonly string[]).includes(normalized)) {
    warnings.push(field + ' "' + candidate + '" is legacy and was normalized to "' + normalized + '"')
    return normalized
  }
  if (candidate) warnings.push('Unknown ' + field + ' "' + candidate + '"; using "' + fallback + '"')
  return fallback
}

