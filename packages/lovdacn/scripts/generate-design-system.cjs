function createPreviewFontLoaderSource() {
  const loaderEntries = Object.entries(fontManifest)
    .map(([key, metadata]) => {
      const faceEntries = Object.entries(metadata.faces)
        .map(([weight, exportName]) => `${weight}: module.${exportName}`)
        .join(", ");
      const aliasEntries = Object.entries(metadata.faces)
        .map(
          ([weight, exportName]) => `${weight}: ${JSON.stringify(exportName)}`,
        )
        .join(", ");
      return `  ${JSON.stringify(key)}: async () => {\n    const module = await import(${JSON.stringify(metadata.package)})\n    const sources = { ${faceEntries} }\n    const aliases = { ${aliasEntries} } as const\n    const unloaded = Object.entries(sources).filter(([weight]) => !Font.isLoaded(aliases[weight as keyof typeof aliases]))\n    if (unloaded.length > 0) {\n      await Font.loadAsync(Object.fromEntries(unloaded.map(([weight, source]) => [aliases[weight as keyof typeof aliases], source])))\n    }\n    return aliases\n  }`;
    })
    .join(",\n");
  return `${GENERATED_HEADER}
import * as Font from 'expo-font'

import type { PresetFont } from '@preview/lib/generated/preset-catalog'

export type FontWeightRole = 'regular' | 'medium' | 'semibold' | 'bold'
export type LoadedFontFaces = Readonly<Record<FontWeightRole, string>>

const LOADERS: Record<PresetFont, () => Promise<LoadedFontFaces>> = {
${loaderEntries}
}

const cache = new Map<PresetFont, Promise<LoadedFontFaces>>()

export function loadPreviewFont(font: PresetFont): Promise<LoadedFontFaces> {
  const cached = cache.get(font)
  if (cached) return cached
  const promise = LOADERS[font]().catch((error) => {
    cache.delete(font)
    throw error
  })
  cache.set(font, promise)
  return promise
}
`;
}

